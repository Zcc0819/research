def sheet(ws, title, rows, widths=None):
    ws.append([title])
    ws.cell(ws.max_row, 1).font = TITLE
    for r in rows:
        ws.append(r)
    # 表头行加粗填色（第一个非空行按调用者约定：rows[1] 为表头时手动处理）
